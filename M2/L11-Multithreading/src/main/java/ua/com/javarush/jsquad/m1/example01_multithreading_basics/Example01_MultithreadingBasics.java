package ua.com.javarush.jsquad.m1.example01_multithreading_basics;

/**
 * Модуль 2. Рівень 11. Знайомство з потоками
 * <hr>
 * <h3>Тема: Багатопотоковість — що це і навіщо</h3>
 *
 * <p>Потоки (треди, англ. <i>threads</i>) використовуються тоді, коли незалежним
 * частинам програми потрібно виконати певний обсяг роботи <b>паралельно</b> з
 * іншими частинами.</p>
 *
 * <h4>Як це працює всередині процесора:</h4>
 * <pre>
 *   • Одноядерний процесор виконує лише одну команду одночасно, але
 *     постійно перемикається між потоками (сотні разів на секунду) —
 *     тому здається, що все виконується одночасно.
 *   • Багатоядерний процесор справді виконує потоки одночасно.
 * </pre>
 *
 * <p><b>Аналогія з життя:</b> кухар один (одне ядро), але готує три страви
 * "паралельно": помішав суп, поставив м'ясо, порізав салат, знову до супу.
 * Він перемикається так швидко, що всі страви готуються "одночасно".</p>
 *
 * <p><b>Реальне застосування:</b> завантаження файлу у фоні, поки інтерфейс
 * програми залишається "живим"; обробка кількох запитів на сервері одночасно.</p>
 */
public class Example01_MultithreadingBasics {

    public static void main(String[] args) {

        // === 1. Головний потік (main thread) ===
        // Будь-яка Java-програма стартує в одному потоці — "головному".
        Thread current = Thread.currentThread();          // отримуємо поточний потік
        System.out.println("=== Головний потік ===");
        System.out.println("Ім'я потоку: " + current.getName());     // зазвичай "main"
        System.out.println("Чи живий: " + current.isAlive());        // true
        System.out.println();

        // === 2. Послідовне виконання (в одному потоці) ===
        // Поки немає додаткових потоків, задачі йдуть строго по черзі.
        System.out.println("=== Послідовно (один потік) ===");
        for (int i = 1; i <= 3; i++) {
            System.out.println("Задача " + i + " виконана");          // 1, потім 2, потім 3
        }
        System.out.println();

        // === 3. Скільки ядер має ця машина ===
        // Показує, скільки потоків реально можуть працювати одночасно.
        int cores = Runtime.getRuntime().availableProcessors();
        System.out.println("=== Можливості процесора ===");
        System.out.println("Доступно логічних ядер: " + cores);
        System.out.println("Стільки потоків можуть виконуватись СПРАВДІ одночасно.");
        System.out.println();

        System.out.println("Головний потік завершує метод main -> програма закінчується.");
    }
}
