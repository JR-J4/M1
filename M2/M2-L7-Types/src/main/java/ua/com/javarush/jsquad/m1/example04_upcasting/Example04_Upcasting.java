package ua.com.javarush.jsquad.m1.example04_upcasting;

/**
 * Модуль 2. Рівень 7. Приведення типів
 * <hr>
 * <h3>Тема: Розширення типу (upcasting) — рух ланцюжком успадкування ВГОРУ</h3>
 *
 * <p>Клас містить усі методи класу, від якого він успадкований, тому об'єкт цього
 * класу можна зберегти у змінній будь-якого з його типів-батьків (аж до {@code Object}).</p>
 *
 * <p>Рух ВГОРУ ланцюжком успадкування (до загальнішого типу) — це <b>розширення типу</b>
 * (воно ж — висхідне перетворення, або <b>upcasting</b>). Воно відбувається
 * <b>автоматично</b>, приведення писати не треба.</p>
 *
 * <pre>
 *   Vehicle v = new Car("Tesla");   // Car "розширили" до Vehicle — автоматично
 * </pre>
 *
 * <p><b>Плата за розширення:</b> через змінну загального типу видно лише методи цього
 * загального типу. Спеціальні методи спадкоємця (напр. {@code openTrunk()}) стають
 * недоступними, хоча об'єкт усередині — усе ще {@code Car}.</p>
 *
 * <p><b>Аналогія з життя:</b> у загальному списку "транспорт компанії" всі машини та
 * мотоцикли записані просто як "транспорт". Зі списку видно тільки те, що спільне для
 * всіх — вони їздять. Хто там із багажником, а хто без — список не показує.</p>
 *
 * <p><b>Реальне застосування:</b> зберігати різні підтипи в одному масиві/списку
 * загального типу й однаково працювати з ними через спільні методи.</p>
 */
public class Example04_Upcasting {

    public static void main(String[] args) {

        // === 1. Розширення відбувається саме собою ===
        System.out.println("=== Upcasting: Car -> Vehicle (автоматично) ===");
        Vehicle vehicle = new Car("Tesla"); // об'єкт Car у змінній типу Vehicle
        vehicle.move();
        // ✔ move() описаний у Vehicle — доступний
        // vehicle.openTrunk();              // ✖ ПОМИЛКА КОМПІЛЯЦІЇ: Vehicle не знає про openTrunk()
        System.out.println("  Через тип Vehicle видно лише move(); openTrunk() недоступний.");
        System.out.println();

        // === 2. Об'єкт не змінюється — "звужений" погляд лише в змінній ===
        System.out.println("=== Об'єкт усередині — усе ще Car ===");
        System.out.println("  vehicle instanceof Car -> " + (vehicle instanceof Car)); // true
        System.out.println("  Розширення змінює тип ЗМІННОЇ, а не сам об'єкт.");
        System.out.println();

        // === 3. Головна вигода: різні підтипи в одному масиві ===
        System.out.println("=== Один масив Vehicle[] — різні транспортні засоби ===");
        Vehicle[] garage = {
                new Car("Audi"),
                new Motorcycle("Harley"),
                new Car("BMW")
        };
        for (Vehicle v : garage) {
            v.move(); // однаковий виклик спільного методу для всіх
        }
        System.out.println();

        System.out.println("Головне: upcasting — автоматичний; ціна — доступ лише до методів загального типу.");
    }
}
