package ua.com.javarush.jsquad.m1.example01_multithreading_downsides;

/**
 * Модуль 2. Рівень 12. Знайомство з потоками. Частина 2
 * <hr>
 * <h3>Тема: Мінуси багатопотоковості — потоки заважають один одному</h3>
 *
 * <p>Потоків кілька, і кожен виконує своє завдання, змінюючи стан спільних
 * об'єктів. Ілюзія одночасності досягається тим, що процесор постійно
 * перемикається з потоку на потік — і перемикання може статися в
 * <b>найменш слушний момент</b>: усередині операції, яку ми вважали "цілою".</p>
 *
 * <h4>Операція count++ насправді складається з трьох кроків:</h4>
 * <pre>
 *   1) прочитати поточне значення count з пам'яті
 *   2) додати 1
 *   3) записати результат назад у count
 * </pre>
 * <p>Якщо між кроками 1 і 3 втрутиться інший потік — одне з оновлень
 * <b>загубиться</b> (race condition, "гонка потоків").</p>
 *
 * <p><b>Аналогія з життя:</b> двоє бухгалтерів одночасно взяли той самий залишок
 * рахунку (100), кожен додав свою суму й записав назад. Замість 100+10+20=130
 * у касі опиниться 120 — один запис затер інший.</p>
 *
 * <p><b>Реальне застосування:</b> лічильники переглядів, залишки товару на складі,
 * баланс рахунку — усе, що змінюють кілька потоків, без захисту рахує неправильно.</p>
 */
public class Example01_MultithreadingDownsides {

    // Спільний лічильник, який будуть збільшувати ДВА потоки одночасно.
    static class Counter {
        volatile int count = 0;              // НЕ захищений — тут і криється проблема

        void increment() {
            count = count + 1;
        }
    }

    public static void main(String[] args) throws InterruptedException {

        System.out.println("=== Мінуси багатопотоковості: гонка за спільним лічильником ===");

        final int TIMES = 1_000_000;
        Counter counter = new Counter();

        // Обидва потоки роблять по TIMES інкрементів ОДНОГО лічильника.
        Runnable job = () -> {
            for (int i = 0; i < TIMES; i++) {
                counter.increment();
            }
        };

        Thread t1 = new Thread(job, "потік-1");
        Thread t2 = new Thread(job, "потік-2");
        t1.start();
        t2.start();

        // Чекаємо завершення обох
        t1.join();
        t2.join();

        int expected = TIMES * 2;
        System.out.println("Очікували: " + expected);
        System.out.println("Отримали:  " + counter.count);
        System.out.println("Загублено оновлень: " + (expected - counter.count));
        System.out.println();
        System.out.println("Значення майже завжди МЕНШЕ за очікуване — частину оновлень");
        System.out.println("затерли одночасні потоки. Як це виправити — в Example02 (synchronized).");
    }
}
