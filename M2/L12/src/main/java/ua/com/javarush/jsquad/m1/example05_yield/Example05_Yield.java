package ua.com.javarush.jsquad.m1.example05_yield;

/**
 * Модуль 2. Рівень 12. Знайомство з потоками. Частина 2
 * <hr>
 * <h3>Тема: Thread.yield() — "поступитися" квантом часу</h3>
 *
 * <p>{@code yield} — <b>статичний</b> метод класу {@code Thread}. Процесор виділяє
 * кожному потоку невеликий проміжок часу — <b>квант</b>. Коли квант спливає,
 * процесор перемикається на інший потік і починає виконувати його команди.</p>
 *
 * <p>Виклик {@code Thread.yield()} дозволяє потоку <b>достроково</b> завершити свій
 * квант і сказати планувальнику: "я поки не поспішаю, можеш дати попрацювати іншим".</p>
 *
 * <p><b>Важливо:</b> yield — це лише <b>підказка</b> планувальнику, а не наказ.
 * Планувальник може її й проігнорувати. Гарантованої черговості yield не дає.</p>
 *
 * <p><b>Аналогія з життя:</b> ти в черзі, але нікуди не поспішаєш і пропускаєш
 * уперед тих, кому терміново. Це ввічливість, а не залізне правило.</p>
 *
 * <p><b>Реальне застосування:</b> у циклі очікування ("busy-wait") yield зменшує
 * марне навантаження на процесор, поступаючись іншим потокам.</p>
 */
public class Example05_Yield {

    public static void main(String[] args) throws InterruptedException {

        System.out.println("=== Thread.yield(): ввічливий фоновий потік ===");

        // Ввічливий потік: після кожного кроку поступається іншим через yield().
        Thread polite = new Thread(() -> {
            for (int i = 1; i <= 5; i++) {
                System.out.println("  ввічливий потік: крок " + i + " -> поступаюся (yield)");
                Thread.yield();     // підказка: "дайте попрацювати іншим"
            }
        }, "polite");

        // Звичайний потік зі своєю роботою.
        Thread busy = new Thread(() -> {
            for (int i = 1; i <= 5; i++) {
                System.out.println("      робочий потік: виконую завдання " + i);
            }
        }, "busy");

        polite.start();
        busy.start();

        polite.join();
        busy.join();

        System.out.println();
        System.out.println("yield лише ПРОСИТЬ планувальник перемкнутися — тому порядок рядків");
        System.out.println("усе одно може відрізнятися від запуску до запуску.");
    }
}
