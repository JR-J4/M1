package ua.com.javarush.jsquad.m1.example04_volatile;

/**
 * Модуль 2. Рівень 12. Знайомство з потоками. Частина 2
 * <hr>
 * <h3>Тема: volatile — щоб зміну змінної "бачили" всі потоки</h3>
 *
 * <p>Щоб працювати швидше, процесор копіює часто вживані змінні у власний
 * <b>кеш</b> (швидку пам'ять) і всі зміни робить там, а в "повільну" оперативну
 * пам'ять записує їх згодом. Проблема: різні потоки (часто на різних ядрах) мають
 * <b>різні кеші</b> й не бачать кеш один одного.</p>
 *
 * <p>Тому один потік може змінити змінну у своєму кеші, а другий цього
 * <b>"не побачить"</b> і працюватиме зі старим значенням — можливо, вічно.</p>
 *
 * <h4>Розв'язання — ключове слово volatile:</h4>
 * <pre>
 *   private volatile boolean stopped = false;
 * </pre>
 * <p>volatile змушує читати й писати цю змінну завжди у <b>спільну</b> (повільну)
 * пам'ять, оминаючи кеш. Тож усі потоки бачать актуальне значення одразу.</p>
 *
 * <p><b>Аналогія з життя:</b> дошка оголошень у під'їзді. Якщо кожен мешканець
 * тримає стару копію вдома (кеш) — новини не дійдуть. volatile — це правило
 * "дивитися лише на спільну дошку", де оголошення завжди свіже.</p>
 *
 * <p><b>Реальне застосування:</b> прапорець зупинки фонового потоку, ознака
 * "конфіг оновлено" чи "з'єднання розірвано" — усе, що один потік ставить, а інші читають.</p>
 */
public class Example04_Volatile {

    // volatile гарантує: коли головний потік поставить stopped = true,
    // фоновий потік ОДРАЗУ це побачить і вийде з циклу.
    static volatile boolean stopped = false;

    public static void main(String[] args) throws InterruptedException {

        System.out.println("=== volatile: сигнал зупинки, який точно буде помічено ===");

        Thread worker = new Thread(() -> {
            long steps = 0;
            while (!stopped) {          // читаємо volatile-прапорець
                steps++;                // корисна "робота"
            }
            System.out.println("фоновий потік помітив stopped=true і зупинився");
            System.out.println("встиг зробити кроків: " + steps);
        }, "worker");

        worker.start();

        Thread.sleep(300);              // хай попрацює трохи
        System.out.println(">>> головний потік: ставлю stopped = true");
        stopped = true;                 // сигнал зупинки — видно всім завдяки volatile

        worker.join();
        System.out.println();
        System.out.println("Без volatile фоновий потік міг би зациклитися назавжди,");
        System.out.println("читаючи застаріле stopped=false зі свого кешу.");
    }
}
