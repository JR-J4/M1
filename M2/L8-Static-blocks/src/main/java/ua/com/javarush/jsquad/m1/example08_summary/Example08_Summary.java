package ua.com.javarush.jsquad.m1.example08_summary;

/**
 * Модуль 2. Рівень 8. Особливості виклику конструкторів. Блок static
 * <hr>
 * <h3>Тема: ПІДСУМОК — повний порядок ініціалізації</h3>
 *
 * <p>Збираємо всі теми лекції разом. При першому {@code new Hero(...)}
 * виконується повний ланцюжок:</p>
 * <ol>
 *   <li>static змінні та static-блоки базового класу (один раз);</li>
 *   <li>static змінні та static-блоки нащадка (один раз);</li>
 *   <li>поля базового класу (для кожного об'єкта);</li>
 *   <li>конструктор базового класу;</li>
 *   <li>поля нащадка;</li>
 *   <li>конструктор нащадка.</li>
 * </ol>
 *
 * <p><b>Сценарій:</b> запуск комп'ютерної гри. Спільні ресурси (карти, музика)
 * завантажуються один раз — це static. А кожен новий герой у грі створюється
 * окремо — це поля та конструктори.</p>
 *
 * <p><b>Реальне застосування:</b> це питання люблять на співбесідах:
 * "у якому порядку виконаються static-блоки, поля та конструктори
 * при створенні об'єкта-нащадка?"</p>
 */
public class Example08_Summary {

    public static void main(String[] args) {


        Test test = new Test(){
            int a = calc();


            int calc(){

                return 2 + 2;
            }

        };


        System.out.println("Гру запущено. Класи ще не завантажені.");
        System.out.println();

        // === 1. Перший герой: спочатку вся static-частина, потім об'єкт ===
        System.out.println("=== new Hero(\"Артем\") — перше звернення до класів ===");
        new Hero("Артем");
        System.out.println();

        // === 2. Другий герой: static уже виконано, лишились поля + конструктори ===
        System.out.println("=== new Hero(\"Соломія\") — класи вже завантажені ===");
        new Hero("Соломія");
        System.out.println();

        // === 3. Повний порядок — шпаргалка ===
        System.out.println("Повний порядок ініціалізації:");
        System.out.println("  1. static базового класу      (один раз)");
        System.out.println("  2. static нащадка             (один раз)");
        System.out.println("  3. поля базового класу        (кожен об'єкт)");
        System.out.println("  4. конструктор базового класу (кожен об'єкт)");
        System.out.println("  5. поля нащадка               (кожен об'єкт)");
        System.out.println("  6. конструктор нащадка        (кожен об'єкт)");
    }
}
