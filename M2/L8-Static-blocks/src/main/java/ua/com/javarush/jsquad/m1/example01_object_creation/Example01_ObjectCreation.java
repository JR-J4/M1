package ua.com.javarush.jsquad.m1.example01_object_creation;

/**
 * Модуль 2. Рівень 8. Особливості виклику конструкторів. Блок static
 * <hr>
 * <h3>Тема: Порядок створення об'єкта</h3>
 *
 * <p>Що насправді відбувається, коли ми пишемо {@code new Order()}?
 * Java-машина виконує чітку послідовність кроків:</p>
 * <ol>
 *   <li>Спочатку виділяється пам'ять під усі змінні — поля класу.
 *       Кожне поле одразу отримує дефолтне значення: {@code 0}, {@code false}, {@code null};</li>
 *   <li>Потім іде ініціалізація базового класу (детально — у Example03);</li>
 *   <li>Потім усім змінним присвоюються значення, якщо вони зазначені (згори вниз);</li>
 *   <li>І нарешті, іде виклик конструктора.</li>
 * </ol>
 *
 * <p><b>Аналогія з життя:</b> заселення в нову квартиру. Спочатку зводять порожню
 * квартиру (пам'ять з дефолтними значеннями), потім завозять меблі (ініціалізація
 * полів), і лише потім заходить господар і наводить свій лад (конструктор).</p>
 *
 * <p><b>Реальне застосування:</b> розуміння цього порядку рятує від багів, коли
 * конструктор чи метод звертається до поля, яке ще не встигло отримати значення.</p>
 */
public class Example01_ObjectCreation {

    public static void main(String[] args) {

        // === 1. Створюємо об'єкт і спостерігаємо за порядком кроків ===
        System.out.println("=== new Order(): дивимось на порядок кроків ===");
        Order order = new Order();
        System.out.println("Замовлення готове: " + order.info());
        System.out.println();

        // === 2. Другий об'єкт — послідовність повторюється для КОЖНОГО new ===
        System.out.println("=== Друге замовлення — ті самі кроки заново ===");
        Order second = new Order();
        System.out.println("Друге замовлення готове: " + second.info());
        System.out.println();

        System.out.println("Головне: спочатку пам'ять і дефолтні значення,");
        System.out.println("потім ініціалізація полів, і лише в кінці — конструктор.");
    }
}

/**
 * Замовлення в інтернет-магазині.
 * Кожен крок створення об'єкта друкує повідомлення, щоб було видно порядок.
 */
class Order {

    // Крок 3: присвоєння значень полям (виконується ПЕРЕД тілом конструктора!)
    private int number = initNumber();
    private String status = initStatus();

    // Крок 4: конструктор виконується останнім
    Order() {
        System.out.println("  Крок 4. Конструктор: замовлення №" + number
                + " зі статусом \"" + status + "\"");
    }

    private int initNumber() {
        // У цей момент виконався лише крок 1: поля мають дефолтні значення.
        // Поле status оголошене НИЖЧЕ, тому воно поки що null
        System.out.println("  Крок 3. Ініціалізація поля number = 1001"
                + " (а status поки що = " + status + ")");
        return 1001;
    }

    private String initStatus() {
        System.out.println("  Крок 3. Ініціалізація поля status = \"НОВЕ\"");
        return "НОВЕ";
    }

    String info() {
        return "№" + number + ", статус: " + status;
    }
}
