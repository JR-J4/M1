package ua.com.javarush.jsquad.m1.example05_static_block;

/**
 * Модуль 2. Рівень 8. Особливості виклику конструкторів. Блок static
 * <hr>
 * <h3>Тема: Статичний блок</h3>
 *
 * <p>Якщо для ініціалізації змінних об'єкта потрібно виконати складний код,
 * ми робимо це в конструкторі. Статичні змінні позбавлені такої можливості —
 * конструктор для них не підходить (він виконується для кожного об'єкта).
 * Для цього до класу додають <b>статичний блок</b> — по суті,
 * "статичний конструктор" класу.</p>
 *
 * <h4>Синтаксис:</h4>
 * <pre>
 *   class Cat {
 *       public static String namePrefix;
 *
 *       static {
 *           // складна ініціалізація static змінних;
 *           // виконується один раз при завантаженні класу
 *       }
 *   }
 * </pre>
 *
 * <p><b>Аналогія з життя:</b> перед відкриттям кав'ярні бариста один раз
 * вмикає та прогріває кавомашину (static-блок). А далі кожне замовлення
 * (конструктор) готується на вже готовому обладнанні.</p>
 *
 * <p><b>Реальне застосування:</b> зчитування конфігурації, підготовка
 * довідників, реєстрація драйверів БД — усе, що треба зробити один раз
 * до створення першого об'єкта.</p>
 */
public class Example05_StaticBlock {

    public static void main(String[] args) {

        // === 1. Static-блок виконується при завантаженні класу, ДО конструктора ===
        System.out.println("=== Створюємо першого кота ===");
        Cat murchyk = new Cat("Мурчик", 5);
        System.out.println("Створено: " + murchyk.getFullName());
        System.out.println();

        // === 2. Другий об'єкт: static-блок уже НЕ виконується ===
        System.out.println("=== Створюємо другого кота ===");
        Cat vasyl = new Cat("Василь");
        System.out.println("Створено: " + vasyl.getFullName());
        System.out.println();

        // === 3. Статичних блоків може бути кілька — виконуються згори вниз ===
        System.out.println("=== Клас із двома static-блоками ===");
        System.out.println("Ліміт на день: " + BankTerminal.dailyLimit + " грн");
        System.out.println();

        System.out.println("Головне: static-блок — це \"конструктор класу\":");
        System.out.println("виконується один раз, при завантаженні, до створення об'єктів.");
    }
}
