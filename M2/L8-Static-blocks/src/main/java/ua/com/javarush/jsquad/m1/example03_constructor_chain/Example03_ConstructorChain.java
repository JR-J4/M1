package ua.com.javarush.jsquad.m1.example03_constructor_chain;

/**
 * Модуль 2. Рівень 8. Особливості виклику конструкторів. Блок static
 * <hr>
 * <h3>Тема: Порядок виклику конструкторів при наслідуванні</h3>
 *
 * <p>Крок 2 зі створення об'єкта — "ініціалізація базового класу".
 * Коли створюється об'єкт класу-нащадка, СПОЧАТКУ повністю відпрацьовує
 * конструктор базового класу, і лише потім — конструктор нащадка.</p>
 *
 * <h4>Синтаксис:</h4>
 * <pre>
 *   class House extends Building {
 *       House() {
 *           // тут компілятор неявно додає super();
 *       }
 *       House(int floors) {
 *           super(floors);   // явний виклик конструктора базового класу
 *       }                    // (має бути ПЕРШИМ рядком конструктора)
 *   }
 * </pre>
 *
 * <p><b>Аналогія з життя:</b> будівництво будинку. Неможливо звести дах раніше
 * за фундамент: спочатку фундамент (базовий клас), потім стіни (нащадок),
 * потім розумна електроніка (нащадок нащадка).</p>
 *
 * <p><b>Реальне застосування:</b> базовий клас гарантує, що його частина об'єкта
 * повністю готова до того, як нащадок почне нею користуватись.</p>
 */
public class Example03_ConstructorChain {

    public static void main(String[] args) {

        // === 1. Два рівні: House -> Building ===
        System.out.println("=== new House(): спочатку Building, потім House ===");
        new House();
        System.out.println();

        // === 2. Три рівні: SmartHouse -> House -> Building ===
        System.out.println("=== new SmartHouse(): ланцюжок з трьох конструкторів ===");
        new SmartHouse();
        System.out.println();

        // === 3. Конструктор з параметрами: super(floors) передає дані вгору ===
        System.out.println("=== new SmartHouse(3): параметр іде вгору по ланцюжку ===");
        new SmartHouse(3);
        System.out.println();

        System.out.println("Головне: конструктори виконуються від базового класу до нащадка,");
        System.out.println("а super(...) мусить бути першим рядком конструктора.");
    }
}
