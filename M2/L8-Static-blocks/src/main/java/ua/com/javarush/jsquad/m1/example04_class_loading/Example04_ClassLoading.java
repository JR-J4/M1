package ua.com.javarush.jsquad.m1.example04_class_loading;

/**
 * Модуль 2. Рівень 8. Особливості виклику конструкторів. Блок static
 * <hr>
 * <h3>Тема: Порядок завантаження класів</h3>
 *
 * <p><b>Java-машина не завантажує класи без необхідності.</b>
 * Як тільки десь у коді відбувається звернення до класу, Java-машина перевіряє,
 * чи його вже завантажено. Якщо ні — завантажує та ініціалізує його.</p>
 *
 * <p><b>Ініціалізація класу</b> — це присвоєння значень усіх його статичних
 * змінних та виклик усіх статичних блоків. Відбувається РІВНО ОДИН РАЗ.</p>
 *
 * <p><b>Аналогія з життя:</b> супермаркет вранці. Каси не вмикають усі одразу —
 * касу №2 "запускають" лише тоді, коли до неї підійшов перший покупець.
 * А коли підходить другий — каса вже працює, вмикати її вдруге не треба.</p>
 *
 * <p><b>Реальне застосування:</b> великі програми мають тисячі класів —
 * ліниве завантаження економить пам'ять і прискорює старт програми.</p>
 */
public class Example04_ClassLoading {

    public static void main(String[] args) {

        System.out.println("Програму запущено. Жоден сервіс ще НЕ завантажено.");
        System.out.println();

        // === 1. Перше звернення до класу -> завантаження та ініціалізація ===
        System.out.println("=== Перший виклик PaymentService.pay() ===");
        // Щойно ми звернулися до класу, JVM завантажила його:
        // присвоїла static змінні та виконала static-блок — і лише потім виконала метод
        PaymentService.pay(100);
        System.out.println();

        // === 2. Друге звернення — клас УЖЕ завантажено ===
        System.out.println("=== Другий виклик PaymentService.pay() ===");
        // Ніякої повторної ініціалізації: static-блок більше не виконується
        PaymentService.pay(50);
        System.out.println();

        // === 3. Інший клас завантажиться лише тоді, коли знадобиться ===
        System.out.println("=== А тепер уперше чіпаємо ReportService ===");
        // Увесь цей час ReportService не завантажувався — він був не потрібен
        ReportService.buildReport();
        System.out.println();

        System.out.println("Головне: клас завантажується при ПЕРШОМУ зверненні до нього,");
        System.out.println("ініціалізація (static змінні + static блоки) виконується один раз.");
    }
}
