package ua.com.javarush.jsquad.m1.example06_field_init_order;

/**
 * Модуль 2. Рівень 8. Особливості виклику конструкторів. Блок static
 * <hr>
 * <h3>Тема: Порядок ініціалізації змінних</h3>
 *
 * <p>Клас завантажується ЗГОРИ ВНИЗ, тому поле класу може звертатися лише до
 * полів, які оголошені ВИЩЕ (їх уже ініціалізовано). Приклад із лекції:</p>
 * <pre>
 *   class Cat {
 *       public int a = 5;
 *       public int b = a + 1;   // можна: a вже ініціалізовано
 *       public int c = a * b;   // можна: a і b вже ініціалізовано
 *   }
 * </pre>
 * <p>Поле {@code b} може звертатися до {@code a}, але нічого не знає про {@code c}.</p>
 *
 * <p>А от порядок оголошення МІЖ методами та полями — не важливий: метод може
 * використовувати будь-які поля, бо він виконується вже після створення об'єкта.</p>
 *
 * <p><b>Аналогія з життя:</b> читання рецепта згори вниз. У кроці 3 можна
 * використати тісто з кроку 1, але не можна "полити глазур'ю з кроку 7" —
 * її ще не приготували.</p>
 *
 * <p><b>Реальне застосування:</b> коли одне поле обчислюється з іншого
 * (ціна з ПДВ із базової ціни) — важливо оголошувати їх у правильному порядку.</p>
 */
public class Example06_FieldInitOrder {

    public static void main(String[] args) {

        // === 1. Поля ініціалізуються згори вниз (приклад із лекції) ===
        System.out.println("=== Cat: поля рахуються згори вниз ===");
        Cat cat = new Cat();
        System.out.println("a = " + cat.a);   // 5
        System.out.println("b = " + cat.b);   // a + 1 = 6
        System.out.println("c = " + cat.c);   // a * b = 30
        System.out.println();

        // === 2. Реальний приклад: ціна товару рахується каскадом ===
        System.out.println("=== Product: кожне наступне поле спирається на попереднє ===");
        Product laptop = new Product();
        System.out.println("Базова ціна:  " + laptop.basePrice + " грн");
        System.out.println("ПДВ (20%):    " + laptop.vat + " грн");
        System.out.println("Ціна з ПДВ:   " + laptop.finalPrice + " грн");
        System.out.println();

        // === 3. Методам порядок оголошення байдужий ===
        System.out.println("=== Метод може стояти вище полів, які використовує ===");
        System.out.println("cat.sum() = " + cat.sum()); // метод оголошено ПЕРШИМ у класі
        System.out.println();

        System.out.println("Головне: поле бачить лише поля, оголошені ВИЩЕ за нього;");
        System.out.println("для методів порядок оголошення не має значення.");
    }
}

/** Приклад із лекції: b може звертатися до a, але нічого не знає про c. */
class Cat {

    // Метод оголошено ДО полів — і це не проблема:
    // методи виконуються вже після повної ініціалізації об'єкта
    public int sum() {
        return a + b + c;
    }

    public int a = 5;
    public int b = a + 1;   // a вже ініціалізовано -> можна


    public int c = a * b;   // a та b вже ініціалізовано -> можна

    // public int d = e + 1;  // ПОМИЛКА КОМПІЛЯЦІЇ: illegal forward reference —
    // public int e = 5;      // поле e оголошене НИЖЧЕ, воно ще не завантажене
}

/** Товар: поля-обчислення каскадом, кожне спирається на попередні. */
class Product {
    public int basePrice = 20_000;
    public int vat = basePrice / 5;              // 20% від базової ціни
    public int finalPrice = basePrice + vat;     // підсумкова ціна
}
