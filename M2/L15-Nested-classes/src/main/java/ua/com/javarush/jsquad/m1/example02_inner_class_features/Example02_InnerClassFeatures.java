package ua.com.javarush.jsquad.m1.example02_inner_class_features;

/**
 * Модуль 2. Рівень 15. Внутрішні та вкладені класи
 * <hr>
 * <h3>Тема: Особливості внутрішніх класів</h3>
 *
 * <p>Усе випливає з однієї речі: <b>у внутрішньому класі є приховане посилання
 * на об'єкт зовнішнього класу</b>. Компілятор непомітно передає його в конструктор
 * внутрішнього класу. Звідси чотири наслідки:</p>
 *
 * <pre>
 *  1. Не можна створити об'єкт внутрішнього класу всередині статичного методу
 *     зовнішнього класу простим new Inner(): нема звідки взяти зовнішній об'єкт.
 *
 *  2. Внутрішній клас не може містити статичні змінні та методи
 *     (правило діяло до Java 16; з Java 16 обмеження зняли).
 *
 *  3. Якщо внутрішній клас оголошено як public, його об'єкти можна створити
 *     за межами зовнішнього класу — але об'єкт зовнішнього класу має бути присутнім:
 *     outer.new Inner().
 *
 *  4. Оскільки в нас два вкладених об'єкти, у методах внутрішнього об'єкта
 *     доступні два посилання this: this і Outer.this.
 * </pre>
 *
 * <p><b>Аналогія з життя:</b> трек у плейлісті. Трек завжди знає, у якому саме
 * плейлісті він лежить (приховане посилання). Тому не можна "створити трек
 * взагалі" — тільки трек у конкретному плейлісті.</p>
 *
 * <p><b>Реальне застосування:</b> {@code Outer.this} рятує, коли імена полів
 * зовнішнього і внутрішнього класів збігаються — типова ситуація в слухачах
 * подій та ітераторах.</p>
 */
public class Example02_InnerClassFeatures {

    public static void main(String[] args) {

        // === Особливість 3: public внутрішній клас створюємо ззовні ===
        // Але тільки маючи об'єкт зовнішнього класу: спершу плейліст, потім трек.
        Playlist rock = new Playlist("Ранковий рок");

        Playlist.Track track1 = rock.new Track("Highway", 215);
        Playlist.Track track2 = rock.new Track("Thunder", 187);

        System.out.println("1. Треки, створені ззовні через rock.new Track(...):");
        track1.printFull();
        track2.printFull();
        System.out.println("   Треків у плейлісті: " + rock.getTrackCount());

        System.out.println();

        // === Особливість 4: два this ===
        // У Track є своє поле name, і в Playlist є поле name. Конфлікту немає:
        //   this.name          → назва треку
        //   Playlist.this.name → назва плейліста
        System.out.println("2. Два this в одному методі printFull():");
        track1.printFull();
        System.out.println("   Зовнішній об'єкт треку — плейліст «" + track1.getOwner().getName() + "»");
        System.out.println("   Це той самий об'єкт, що й rock? " + (track1.getOwner() == rock));

        System.out.println();

        // === Особливість 1: статичний метод зовнішнього класу ===
        // Усередині static-методу немає this, тому new Track(...) не компілюється.
        // Вихід — створити зовнішній об'єкт явно (див. Playlist.createDemoTrack()).
        System.out.println("3. Трек, створений у статичному методі зовнішнього класу:");
        Playlist.Track demo = Playlist.createDemoTrack();
        demo.printFull();

        System.out.println();

        // === Особливість 2: статичні члени внутрішнього класу ===
        // Класичне правило з підручників: "внутрішній клас не може мати static".
        // Правда станом до Java 15. Java 16 (JEP 395, разом із record) обмеження зняла.
        System.out.println("4. Статичний лічильник усередині внутрішнього класу:");
        System.out.println("   Усього створено треків: " + Playlist.Track.getTotalTracksEverCreated());
        System.out.println("   (на Java <= 15 такий код навіть не скомпілювався б)");

        System.out.println();

        // === 5. Головне обмеження, яке нікуди не зникло ===
        // Внутрішній об'єкт НЕ ІСНУЄ без зовнішнього:
        //   Playlist.Track ghost = new Playlist.Track("X", 10);   // не компілюється
        // А ще: внутрішній об'єкт тримає зовнішній у пам'яті, поки живий сам.
        System.out.println("5. Внутрішній об'єкт тримає зовнішній живим:");
        System.out.println("   Поки живе Track, збирач сміття не прибере його Playlist —");
        System.out.println("   бо в треку лежить приховане посилання Playlist.this.");
        System.out.println("   Якщо посилання на зовнішній об'єкт не потрібне — беріть static (див. приклад 03).");
    }
}
