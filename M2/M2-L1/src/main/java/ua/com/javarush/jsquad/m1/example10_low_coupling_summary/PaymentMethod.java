package ua.com.javarush.jsquad.m1.example10_low_coupling_summary;

/**
 * Інтерфейс способу оплати — "чіткий контракт" між магазином і платіжними системами.
 *
 * <p>Це і є <b>слабка зв'язність</b>: магазин знає лише про цей інтерфейс, а не про
 * конкретні класи. Один шар (магазин) звертається до іншого (оплата) через невелику,
 * суворо регламентовану частину — лише метод {@code pay()}.</p>
 */
public interface PaymentMethod {

    /** Провести оплату на вказану суму. Повертає true, якщо успішно. */
    boolean pay(double amount);

    /** Назва способу оплати — для чека. */
    String name();
}
