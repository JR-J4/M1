package ua.com.javarush.jsquad.m1.example02_abstraction;

/**
 * Абстрактний клас Figure (Геометрична фігура).
 *
 * <p><b>Абстракція в дії:</b> ми НЕ знаємо, як саме рахувати площу для "фігури взагалі",
 * але точно знаємо, що будь-яка фігура <i>має</i> площу і назву. Це і є виділення
 * головних характеристик та відкидання другорядних.</p>
 *
 * <p>Слово {@code abstract} біля методу {@code area()} означає: "метод оголошено,
 * але реалізації немає — її зобов'язаний дати кожен нащадок".</p>
 *
 * <pre>
 *              ┌───────────────────────┐
 *              │   Figure (abstract)   │  ← не можна створити new Figure()!
 *              │  + name               │
 *              │  + area()  ← abstract │
 *              └───────────┬───────────┘
 *                ┌─────────┴──────────┐
 *          ┌─────┴──────┐      ┌──────┴──────┐
 *          │   Circle   │      │  Rectangle  │
 *          │ area()=πr² │      │ area()= w·h │
 *          └────────────┘      └─────────────┘
 * </pre>
 */
public abstract class Figure {

    // Спільна характеристика всіх фігур (абстрагувались від кольору, товщини ліній тощо)
    protected String name;

    public Figure(String name) {
        this.name = name;
    }

    // Абстрактний метод: КОЖНА фігура рахує площу, але кожна — по-своєму.
    // Тіла немає — лише оголошення. Реалізацію дають нащадки.
    public abstract double area();

    // Звичайний метод — спільний для всіх фігур, користується абстрактним area()
    public void printArea() {
        System.out.printf("  %s: площа = %.2f%n", name, area());
    }
}
