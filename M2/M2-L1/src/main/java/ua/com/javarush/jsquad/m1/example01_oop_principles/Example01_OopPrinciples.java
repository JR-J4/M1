package ua.com.javarush.jsquad.m1.example01_oop_principles;

/**
 * Модуль 2. Рівень 1. ООП: інкапсуляція, поліморфізм
 * <hr>
 * <h3>Тема: ООП — 4 основні принципи (огляд)</h3>
 *
 * <p><b>ООП — це принципи. Внутрішні закони.</b> Кожен із них у чомусь нас обмежує,
 * але натомість дає великі переваги, коли програма виростає до великих розмірів.</p>
 *
 * <p><b>Аналогія з життя (зі слайду лекції):</b>
 * Чотири принципи ООП — це як чотири ніжки стільця. Якщо прибрати хоча б одну —
 * вся система стане нестійкою.</p>
 *
 * <pre>
 *  ┌──────────────────────────────────────────────────────────┐
 *  │                        О О П                              │
 *  │                                                           │
 *  │  ┌──────────────┐   ┌──────────────┐                      │
 *  │  │  АБСТРАКЦІЯ   │   │ ІНКАПСУЛЯЦІЯ  │                      │
 *  │  │ виділяємо     │   │ ховаємо дані │                      │
 *  │  │ головне       │   │ за методами  │                      │
 *  │  └──────────────┘   └──────────────┘                      │
 *  │  ┌──────────────┐   ┌──────────────┐                      │
 *  │  │ УСПАДКУВАННЯ  │   │ ПОЛІМОРФІЗМ   │                      │
 *  │  │ нащадок бере  │   │ один виклик —│                      │
 *  │  │ від батька    │   │ різна логіка │                      │
 *  │  └──────────────┘   └──────────────┘                      │
 *  │       ▲ 4 ніжки одного стільця ▲                          │
 *  └──────────────────────────────────────────────────────────┘
 * </pre>
 *
 * <p><b>Реальне застосування:</b> будь-яка серйозна Java-програма (банк, інтернет-магазин,
 * месенджер) побудована на цих 4 принципах. Цей приклад показує всі 4 на одному
 * простому об'єкті — смартфоні.</p>
 */
public class Example01_OopPrinciples {

    public static void main(String[] args) {

        // === 1. АБСТРАКЦІЯ — виділяємо лише важливе ===
        // Реальний телефон має сотні характеристик. Ми лишили 3: модель, власник, заряд.
        System.out.println("=== 1. АБСТРАКЦІЯ ===");
        System.out.println("Реальний смартфон             Наш клас Smartphone");
        System.out.println("┌────────────────────┐        ┌──────────────────┐");
        System.out.println("│ модель             │ ────>  │ model     ✔      │");
        System.out.println("│ власник            │ ────>  │ owner     ✔      │");
        System.out.println("│ заряд батареї      │ ────>  │ battery   ✔      │");
        System.out.println("│ матеріал корпусу   │ ──X    │                  │");
        System.out.println("│ кількість пікселів │ ──X    │ зайве відкинуто! │");
        System.out.println("│ модель Wi-Fi чипа  │ ──X    │                  │");
        System.out.println("└────────────────────┘        └──────────────────┘");
        System.out.println();

        Smartphone phone = new Smartphone("Galaxy A54", "Олена");

        // === 2. ІНКАПСУЛЯЦІЯ — дані приховані за методами ===
        // Ми не можемо написати phone.battery = 200 — поле private.
        // Працюємо лише через методи, які контролюють значення.
        System.out.println("=== 2. ІНКАПСУЛЯЦІЯ ===");
        System.out.println("Заряд нового телефону: " + phone.getBattery() + "%");
        // phone.battery = 200;     // ПОМИЛКА КОМПІЛЯЦІЇ — поле private!
        phone.charge(50);            // метод сам обмежує заряд до 100%
        System.out.println("Поле battery приховане — зіпсувати дані ззовні неможливо.");
        System.out.println();

        // === 3. УСПАДКУВАННЯ — новий клас на основі існуючого ===
        // GamingPhone отримав model, owner, battery, charge() від Smartphone "безкоштовно".
        System.out.println("=== 3. УСПАДКУВАННЯ ===");
        GamingPhone gaming = new GamingPhone("ROG Phone 8", "Максим");
        System.out.println("GamingPhone успадкував поля та методи Smartphone:");
        System.out.println("  власник = " + gaming.getOwner() + ", заряд = " + gaming.getBattery() + "%");
        gaming.charge(10); // метод charge() взято від батька без жодного рядка коду
        System.out.println();

        // === 4. ПОЛІМОРФІЗМ — один виклик, різна поведінка ===
        // Той самий powerOn() працює по-різному залежно від типу об'єкта.
        System.out.println("=== 4. ПОЛІМОРФІЗМ ===");
        Smartphone[] devices = { phone, gaming }; // масив батьківського типу!
        for (Smartphone device : devices) {
            device.powerOn(); // кожен вмикається по-своєму
        }
        System.out.println();
        System.out.println("Один метод powerOn() — дві різні реалізації. Це поліморфізм.");
        System.out.println();

        System.out.println("Усі 4 принципи разом тримають програму \"стійкою\", як 4 ніжки стільця.");
    }
}
