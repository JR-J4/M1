package ua.com.javarush.jsquad.m1.example02_abstraction;

/**
 * Модуль 2. Рівень 1. ООП: інкапсуляція, поліморфізм
 * <hr>
 * <h3>Тема: Абстракція</h3>
 *
 * <p><b>Абстракція — це розділення чогось великого, монолітного, на безліч маленьких
 * складових.</b> Це правильне розділення програми на об'єкти. Абстракція дозволяє
 * <b>відібрати головні характеристики</b> та пропустити другорядні.</p>
 *
 * <p><b>Аналогія з життя:</b> коли ви кажете "намалюй фігуру", ви не уточнюєте колір
 * чи товщину олівця — ви виділяєте суть: "фігура має форму й площу". Деталі залежать
 * від конкретної фігури.</p>
 *
 * <h4>Інструмент абстракції в Java — абстрактний клас:</h4>
 * <pre>
 *   abstract class Figure {
 *       abstract double area();   // ЩО треба вміти (без ЯК)
 *   }
 * </pre>
 * Абстрактний клас каже "що" повинні вміти нащадки, але не каже "як".
 * "Як" вирішує кожен конкретний клас ({@link Circle}, {@link Rectangle}).
 *
 * <p><b>Реальне застосування:</b> графічний редактор працює з «фігурами взагалі»
 * (Figure), не знаючи, коло це чи прямокутник. Додати нову фігуру = додати новий клас,
 * не чіпаючи старий код.</p>
 */
public class Example02_Abstraction {

    public static void main(String[] args) {

        // === 1. Не можна створити "фігуру взагалі" ===
        // Figure f = new Figure("щось"); // ПОМИЛКА: Figure — abstract!
        System.out.println("=== Абстракція: \"фігура взагалі\" не існує ===");
        System.out.println("new Figure() — заборонено компілятором.");
        System.out.println("Існують лише КОНКРЕТНІ фігури: коло, прямокутник...");
        System.out.println();

        // === 2. Працюємо з конкретними фігурами ===
        Circle circle = new Circle(5);
        Rectangle rectangle = new Rectangle(4, 6);

        System.out.println("=== Кожна фігура рахує площу ПО-СВОЄМУ ===");
        circle.printArea();    // використає area() кола: πr²
        rectangle.printArea(); // використає area() прямокутника: w·h
        System.out.println();

        // === 3. Сила абстракції: працюємо зі списком "просто фігур" ===
        // Нам байдуже, що там усередині — головне, що всі вони вміють area().
        System.out.println("=== Малюємо креслення (масив абстрактних Figure) ===");
        Figure[] drawing = {
                new Circle(1),
                new Rectangle(2, 3),
                new Circle(10)
        };

        double total = 0;
        for (Figure figure : drawing) {
            figure.printArea();
            total += figure.area(); // спільний інтерфейс — не питаємо тип!
        }
        System.out.printf("Загальна площа креслення: %.2f%n", total);
        System.out.println();

        System.out.println("Абстракція = виділили суть (\"фігура має площу\"),");
        System.out.println("а деталі реалізації лишили конкретним класам.");
    }
}
