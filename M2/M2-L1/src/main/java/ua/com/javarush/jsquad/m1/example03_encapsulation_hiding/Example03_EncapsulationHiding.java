package ua.com.javarush.jsquad.m1.example03_encapsulation_hiding;

/**
 * Модуль 2. Рівень 1. ООП: інкапсуляція, поліморфізм
 * <hr>
 * <h3>Тема: Інкапсуляція — приховування реалізації</h3>
 *
 * <p><b>Мета інкапсуляції — покращити якість взаємодії речей завдяки їх спрощенню.</b>
 * З точки зору програмування інкапсуляція — це «приховування реалізації». Усі «нутрощі»
 * програми приховані від користувача: для нього вони зайві. Користувачу потрібен
 * результат, а не внутрішній процес.</p>
 *
 * <p><b>Аналогія з життя (зі слайду):</b> не має значення, що відбувається в автомобіля
 * всередині. Головне — при натисканні правої педалі авто їде вперед, а при натисканні
 * лівої — гальмує. Так само й кавомашина: одна кнопка → готова кава.</p>
 *
 * <p>«Капсула» в Java — це <b>клас</b>. Він об'єднує дані й методи в одному пакуванні,
 * а зайве ховає за модифікатором {@code private}.</p>
 *
 * <p><b>Реальне застосування:</b> бібліотеки та API. Ви викликаєте
 * {@code list.add(x)} або {@code Collections.sort(list)} — і не знаєте (та й не мусите
 * знати), що там усередині. Складність прихована.</p>
 */
public class Example03_EncapsulationHiding {

    public static void main(String[] args) {

        CoffeeMachine machine = new CoffeeMachine();

        // === 1. Користувач натискає ОДНУ кнопку ===
        System.out.println("=== Простий публічний інтерфейс ===");
        System.out.println();

        // === 2. Усе складне приховано ===
        // machine.grindBeans();  // ПОМИЛКА КОМПІЛЯЦІЇ: метод private!
        // machine.heatWater();   // ПОМИЛКА КОМПІЛЯЦІЇ: метод private!
        System.out.println("=== Що приховано від користувача ===");
        System.out.println("grindBeans(), heatWater(), frothMilk() — усі private.");
        System.out.println("Викликати їх ззовні неможливо — компілятор не дозволить.");
        System.out.println();

        // === 3. Чому це добре? ===
        System.out.println("=== Переваги приховування реалізації ===");
        System.out.println("• Простота: користувач бачить 1 кнопку, а не 3 кроки.");
        System.out.println("• Свобода змін: можна переписати grindBeans() як завгодно —");
        System.out.println("  зовнішній код не зламається, бо він про цей метод не знає.");
        System.out.println("• Безпека: ніхто не запустить нагрів води в неправильний момент.");
    }
}
