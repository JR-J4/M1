package ua.com.javarush.jsquad.m1.example05_getters_setters;

/**
 * Модуль 2. Рівень 1. ООП: інкапсуляція, поліморфізм
 * <hr>
 * <h3>Тема: Інкапсуляція — гетери, сетери та переваги</h3>
 *
 * <p>Із приховуванням даних нам допомагають модифікатори доступу <b>та геттери і сеттери</b>.
 * Поле приховуємо ({@code private}), а доступ даємо через методи, які можуть
 * перевіряти й контролювати значення.</p>
 *
 * <h4>Переваги інкапсуляції зі слайду лекції:</h4>
 * <ol>
 *   <li><b>Валідний внутрішній стан</b> — об'єкт сам стежить за змінами своїх даних
 *       (баланс не стане від'ємним).</li>
 *   <li><b>Контроль аргументів</b> — перевіряємо все, що передається.</li>
 *   <li><b>Мінімізація помилок</b> при зміні коду — приватну реалізацію можна
 *       переписати, і зовнішній код далі працюватиме.</li>
 *   <li><b>Задаємо спосіб взаємодії</b> об'єкта зі стороннім кодом.</li>
 * </ol>
 *
 * <p><b>Аналогія з життя:</b> ви не лізете в банк руками по гроші. Ви подаєте
 * запит ("поповнити", "зняти"), а банк перевіряє його за своїми правилами.</p>
 *
 * <p><b>Чому без сетера для balance?</b> Бо "просто присвоїти баланс" — небезпечно.
 * Тому є лише {@code getBalance()} (читання) та методи {@code deposit/withdraw} з перевірками.</p>
 */
public class Example05_GettersSetters {

    public static void main(String[] args) {

        BankAccount account = new BankAccount("Андрій");

        // === 1. Нормальні операції проходять перевірку ===
        System.out.println("=== Коректні операції ===");
        account.deposit(1000);
        account.withdraw(300);
        System.out.println("Баланс через getter: " + account.getBalance());
        System.out.println();

        // === 2. Валідний внутрішній стан: не даємо піти в мінус ===
        System.out.println("=== Захист стану: зняти більше, ніж є ===");
        account.withdraw(5000); // буде відхилено — недостатньо коштів
        System.out.println();

        // === 3. Контроль аргументів: від'ємна сума недопустима ===
        System.out.println("=== Контроль аргументів: deposit(-500) ===");
        try {
            account.deposit(-500); // викине IllegalArgumentException
        } catch (IllegalArgumentException e) {
            System.out.println("  Спіймано виняток: " + e.getMessage());
        }
        System.out.println();

        // === 4. Прямий доступ до поля заборонено ===
        // account.balance = 1_000_000; // ПОМИЛКА КОМПІЛЯЦІЇ: поле private!
        System.out.println("=== Прямий злом неможливий ===");
        System.out.println("account.balance = 1000000;  ← так зробити НЕ можна (private).");
        System.out.println("Підсумок балансу залишився чесним: " + account.getBalance());
    }
}
